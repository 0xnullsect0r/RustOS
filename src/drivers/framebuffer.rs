const CHAR_W: usize = 8;
const CHAR_H: usize = 8;

// ---------------------------------------------------------------------------
// Framebuffer writer
// ---------------------------------------------------------------------------

pub struct FramebufferWriter {
    fb: *mut u8,
    info: FrameBufferInfo,
    col: usize,
    row: usize,
    fg: [u8; 3], // R, G, B
    bg: [u8; 3],
}

// SAFETY: the framebuffer pointer is a unique, globally-allocated MMIO mapping
// that is only ever accessed through this protected mutex.
unsafe impl Send for FramebufferWriter {}

impl FramebufferWriter {
    pub fn new(fb: *mut u8, info: FrameBufferInfo) -> Self {
        FramebufferWriter {
            fb,
            info,
            col: 0,
            row: 0,
            fg: [0xFF, 0xFF, 0xFF], // white
            bg: [0x00, 0x00, 0x00], // black
        }
    }

    fn cols(&self) -> usize {
        self.info.width / CHAR_W
    }
    fn rows(&self) -> usize {
        self.info.height / CHAR_H
    }

    fn write_pixel(&mut self, x: usize, y: usize, rgb: [u8; 3]) {
        if x >= self.info.width || y >= self.info.height {
            return;
        }
        let bpp = self.info.bytes_per_pixel;
        let offset = (y * self.info.stride + x) * bpp;
        let pixel =
            unsafe { core::slice::from_raw_parts_mut(self.fb.add(offset), bpp) };
        match self.info.pixel_format {
            PixelFormat::Rgb => {
                pixel[0] = rgb[0];
                pixel[1] = rgb[1];
                pixel[2] = rgb[2];
                if bpp > 3 {
                    pixel[3] = 0xFF;
                }
            }
            PixelFormat::Bgr => {
                pixel[0] = rgb[2];
                pixel[1] = rgb[1];
                pixel[2] = rgb[0];
                if bpp > 3 {
                    pixel[3] = 0xFF;
                }
            }
            _ => {
                // Unknown: try RGB order
                pixel[0] = rgb[0];
                if bpp > 1 {
                    pixel[1] = rgb[1];
                }
                if bpp > 2 {
                    pixel[2] = rgb[2];
                }
            }
        }
    }

    fn draw_glyph(&mut self, ascii: u8, col: usize, row: usize) {
        let idx = if ascii >= 0x20 && ascii <= 0x7F {
            (ascii - 0x20) as usize
        } else {
            0 // space for non-printable
        };
        let glyph = FONT[idx];
        let px0 = col * CHAR_W;
        let py0 = row * CHAR_H;
        for (y, &bits) in glyph.iter().enumerate() {
            for x in 0..CHAR_W {
                let on = (bits >> (7 - x)) & 1 != 0;
                let color = if on { self.fg } else { self.bg };
                self.write_pixel(px0 + x, py0 + y, color);
            }
        }
    }

    fn scroll_up(&mut self) {
        let bpp = self.info.bytes_per_pixel;
        let stride = self.info.stride;
        let line_bytes = stride * CHAR_H * bpp;
        let total_bytes = stride * self.info.height * bpp;
        unsafe {
            core::ptr::copy(
                self.fb.add(line_bytes),
                self.fb,
                total_bytes - line_bytes,
            );
            core::ptr::write_bytes(self.fb.add(total_bytes - line_bytes), 0, line_bytes);
        }
    }

    pub fn clear(&mut self) {
        let total = self.info.stride * self.info.height * self.info.bytes_per_pixel;
        unsafe {
            core::ptr::write_bytes(self.fb, 0, total);
        }
        self.col = 0;
        self.row = 0;
    }

    pub fn set_colors(&mut self, fg: [u8; 3], bg: [u8; 3]) {
        self.fg = fg;
        self.bg = bg;
    }

    pub fn write_char(&mut self, c: char) {
        match c {
            '\n' => {
                self.col = 0;
                self.row += 1;
            }
            '\r' => {
                self.col = 0;
            }
            '\x08' => {
                // Backspace: erase previous character cell
                if self.col > 0 {
                    self.col -= 1;
                }
                self.draw_glyph(b' ', self.col, self.row);
                return;
            }
            c => {
                let byte = if c.is_ascii() { c as u8 } else { b'?' };
                self.draw_glyph(byte, self.col, self.row);
                self.col += 1;
                if self.col >= self.cols() {
                    self.col = 0;
                    self.row += 1;
                }
            }
        }
        if self.row >= self.rows() {
            self.scroll_up();
            self.row = self.rows() - 1;
        }
    }
}

impl fmt::Write for FramebufferWriter {
    fn write_str(&mut self, s: &str) -> fmt::Result {
        for c in s.chars() {
            self.write_char(c);
        }
        Ok(())
    }
}

// ---------------------------------------------------------------------------
// Global singleton
// ---------------------------------------------------------------------------

lazy_static! {
    pub static ref FRAMEBUFFER: Mutex<Option<FramebufferWriter>> = Mutex::new(None);
}

/// Initialise the framebuffer writer.  Called once from `kernel_main` with the
/// pointer and layout info provided by the UEFI bootloader.
pub fn init(fb: *mut u8, info: FrameBufferInfo) {
    let mut writer = FramebufferWriter::new(fb, info);
    writer.clear();
    *FRAMEBUFFER.lock() = Some(writer);
}

/// Print formatted text to the framebuffer (if initialised).
///
/// Uses `try_lock` so recursive calls from exception handlers do not deadlock.
#[doc(hidden)]
pub fn _print(args: fmt::Arguments) {
    use core::fmt::Write;
    use x86_64::instructions::interrupts;
    interrupts::without_interrupts(|| {
        if let Some(mut guard) = FRAMEBUFFER.try_lock() {
            if let Some(ref mut w) = *guard {
                let _ = w.write_fmt(args);
            }
        }
    });
}
